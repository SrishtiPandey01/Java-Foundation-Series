public class PythagoreanTriplet {
    public static void main(String[] args) {
        int a = 3;
        int b = 4;
        int c = 5;

        if ((a * a) + (b * b) == (c * c)) {
            System.out.println("Pythagorean triplet");
        } else {
            System.out.println("Not a Pythagorean triplet");
        }
    }
}
