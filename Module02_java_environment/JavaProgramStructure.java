public class JavaProgramStructure {
    public static void main(String[] args) {
        System.out.println("Java Program Structure:");
        System.out.println("1. Class Declaration: The class is declared using the 'class' keyword followed by the class name.");
        System.out.println("2. Main Method: The main method is the entry point of the program and is defined as 'public static void main(String[] args)'.");
        System.out.println("3. Statements: Inside the main method, you can write statements to perform actions, such as printing to the console.");
    }   
}
