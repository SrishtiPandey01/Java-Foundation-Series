//package Java-Foundation-Series.Module03_OperatorsAndExpressions;

public class LogicalOperators {
    public static void main(String[] args) {
        boolean a = true;
        boolean b = false;

        // AND
        System.out.println("a && b: " + (a && b));

        // OR
        System.out.println("a || b: " + (a || b));

        // NOT
        System.out.println("!a: " + (!a));
    }
}
