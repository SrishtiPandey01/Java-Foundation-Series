public class Data_Type_Demo {
    public static void main(String[] args) {
        byte myByte = 100; // Byte (whole number)
        short myShort = 5000; // Short (whole number)
        int myNum = 5; // Integer (whole number)
        long myLong = 15000000000L; // Long (whole number)
        float myFloatNum = 5.99f; // Floating point number
        double myDoubleNum = 9.98; // Double (floating point number)
        char myLetter = 'D'; // Character
        boolean myBool = true; // Boolean
        String myText = "Hello"; // String

        System.out.println("Byte: " + myByte);
        System.out.println("Short: " + myShort);
        System.out.println("Integer: " + myNum);
        System.out.println("Long: " + myLong);
        System.out.println("Float: " + myFloatNum);
        System.out.println("Double: " + myDoubleNum);
        System.out.println("Character: " + myLetter);
        System.out.println("Boolean: " + myBool);
        System.out.println("String: " + myText);
    }

}
