public class Variables {
    public static void main(String[] args) {
        // Variable declaration and initialization
        int myNum = 5; // Integer variable
        double myDouble = 5.99; // Double variable
        char myLetter = 'D'; // Character variable
        boolean myBool = true; // Boolean variable
        String myText = "Hello"; // String variable

        // Output the values of the variables
        System.out.println("Integer: " + myNum);
        System.out.println("Double: " + myDouble);
        System.out.println("Character: " + myLetter);
        System.out.println("Boolean: " + myBool);
        System.out.println("String: " + myText);
    }
}
